export function setLang(next) {
  lang = SUPPORTED_LANGS.includes(next) ? next : "en";
  state.lang = lang;
  document.documentElement.lang = lang;
  document.title = t("game.title");
}

export function getLang() {
  return lang;
}

export function t(key, vars = {}) {
  const table = UI[lang] || UI.en;
  let value = table[key] ?? UI.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    value = value.replaceAll(`{${k}}`, String(v));
  }
  return value;
}

function withName(value) {
  const str = String(value);
  return str.replaceAll("{name}", state.name);
}

export function L(value) {
  if (value == null) return "";
  if (typeof value === "string") return withName(value);
  if (Array.isArray(value)) return value.map((entry) => (typeof entry === "string" ? withName(entry) : entry));
  const selected = value[lang] ?? value.en ?? "";
  if (Array.isArray(selected)) return selected.map((entry) => (typeof entry === "string" ? withName(entry) : entry));
  return withName(selected);
}

